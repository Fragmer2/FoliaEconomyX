package me.yourname.burzhuy.quest;

/**
 * Enum representing different types of quests
 */
public enum QuestType {
    MOB_KILL,           // Kill specific mobs
    ITEM_DELIVER,       // Deliver items to NPC
    BLOCK_BREAK,        // Mine specific blocks
    ITEM_CRAFT,         // Craft specific items
    TRAVEL,             // Travel to dimensions
    WALK_DISTANCE,      // Walk a certain distance
    WALK_ON_WATER,      // Walk on water
    VISIT_OCEAN,        // Visit ocean biome
    JUMP,               // Jump X times
    USE_TOTEM,          // Use totem of undying
    DRINK_POTION,       // Drink potions
    GET_ITEM            // Obtain specific item
}
